export function agendaOverview(items: { title: string; duration: string | null; owner: string | null }[]) {
  return items.filter((item) => !(item.owner === 'Host' && /^\d+m$/.test(item.duration ?? ''))).map((item) => item.title)
}

export function zoomPassword(contents: string) {
  return contents.match(/^\s*[-*]?[^\S\r\n]*[*_]*(?:Zoom )?(?:password|passcode)[*_]*:[*_]*[ \t]+(.+?)\s*$/im)?.[1].trim()
}

export function tentative(topics: boolean, participants: boolean) {
  if (topics && participants) return ''
  const missing = [!topics && 'agenda items', !participants && 'attendees'].filter(Boolean).join(' or ')
  return `**Be first**: no ${missing} yet; add yourself (and optionally a topic!) to the agenda early to encourage others to do the same. If no-one turns up within 5 minutes of the meeting start, assume that the meeting will not proceed.`
}
